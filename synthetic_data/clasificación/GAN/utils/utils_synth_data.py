def decode_one_hot_to_sequence(one_hot_sequence):
    """
    Decodifica una secuencia one-hot a una secuencia de DNA
    """
    indices = np.argmax(one_hot_sequence, axis=-1)
    base_map = {i: base for i, base in enumerate(DNA_BASES)}
    sequence = "".join([base_map.get(idx, 'N') for idx in indices])
    return sequence.replace('N', '')


def generate_synthetic_sequences(generator, target_class_idx,
                                 num_samples_to_generate):
    """
    Genera secuencias sinteticas condicionadas a una clase.
    """
    print(
        f"  -> Generando {num_samples_to_generate} muestras para la clase {target_class_idx}..."
    )
    noise = tf.random.normal(shape=(num_samples_to_generate, NOISE_DIM))
    target_labels = tf.one_hot([target_class_idx] * num_samples_to_generate,
                               depth=NUM_CLASSES)
    synthetic_oh = generator([noise, target_labels], training=False).numpy()

    synthetic_sequences = []
    inv_superf_dict = {v: k for k, v in SUPERF_DICT.items()}
    class_name = inv_superf_dict[target_class_idx]

    for i, oh_seq in enumerate(synthetic_oh):
        seq = decode_one_hot_to_sequence(oh_seq)
        record = SeqIO.SeqRecord(
            Seq(seq),
            id=f"Synthetic_TE_{class_name}_{i:05d}",
            description=f"Generated by cGAN for class: {class_name}",
        )
        record.seq = record.seq.lower()

        order_name = SUPERF_TO_ORDER.get(class_name.upper(), "UNKNOWN")
        record.id = f"{record.id}#{order_name}/{class_name}"
        synthetic_sequences.append(record)
    return synthetic_sequences


def jensen_shannon_divergence(P, Q):
    """
    Calcula la distancia de JSD entre dos distribuciones
    """
    P = P / np.sum(P)
    Q = Q / np.sum(Q)
    M = 0.5 * (P + Q)

    P_non_zero = P[P > 0]
    M_for_P = M[P > 0]
    dkl_p = np.sum(P_non_zero * np.log2(P_non_zero / M_for_P))

    Q_non_zero = Q[Q > 0]
    M_for_Q = M[Q > 0]
    dkl_q = np.sum(Q_non_zero * np.log2(Q_non_zero / M_for_Q))

    return (0.5 * dkl_p + 0.5 * dkl_q)


