def get_species_data(fasta_path, species_regex):
    """
    Construye mapas de especie a secuencias reales y a conteos por clase
    """
    species_to_sequences = {}
    species_to_class_counts = {}
    for record in SeqIO.parse(fasta_path, "fasta"):
        species_id = extract_species_id(record.id, species_regex)
        class_idx = get_label_data(record.id)
        if class_idx == -1:
            continue
        species_to_sequences.setdefault(species_id,
                                        []).append(str(record.seq).upper())
        species_to_class_counts.setdefault(species_id, Counter())
        species_to_class_counts[species_id][class_idx] += 1
    return species_to_sequences, species_to_class_counts


def kneedle_knee_point(x_vals, y_vals):
    """
    Detecta el punto de codo por distancia máxima a la línea entre extremos
    """
    if len(x_vals) < 3:
        return len(x_vals) - 1
    x0, y0 = x_vals[0], y_vals[0]
    xN, yN = x_vals[-1], y_vals[-1]
    dx = xN - x0
    dy = yN - y0
    denom = (dx**2 + dy**2)**0.5 or 1.0
    max_dist = -1.0
    knee_idx = len(x_vals) - 1
    for i in range(1, len(x_vals) - 1):
        xi, yi = x_vals[i], y_vals[i]
        num = abs(dy * (xi - x0) - dx * (yi - y0))
        dist = num / denom
        if dist > max_dist:
            max_dist = dist
            knee_idx = i
    return knee_idx


